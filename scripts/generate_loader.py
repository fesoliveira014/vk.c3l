#!/usr/bin/env python3
"""Generate loader_entry_points.c3 from the core commands of commands.c3.

Every `extern fn ... @cname("vkName");` line of commands.c3 gets a function
pointer slot and an exported definition of `vkName` that calls through it, so
neither the binding nor a static library compiled against the Vulkan headers
(VMA) needs the loader at link time. `--check` fails when the committed file
differs from what the commands produce.
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COMMANDS = ROOT / "commands.c3"
OUTPUT = ROOT / "loader_entry_points.c3"

EXTERN = re.compile(
    r'^extern fn (?P<ret>.+?) (?P<name>\w+)\((?P<params>.*)\) @cname\("(?P<symbol>vk\w+)"\);\s*$'
)

# Commands an application calls before it holds an instance: their entry
# points open the loader on first use, so a program that never calls
# vk::load_loader keeps working.
GLOBAL_COMMANDS = {
    "vkCreateInstance": "Result.ERROR_INITIALIZATION_FAILED",
    "vkEnumerateInstanceVersion": "Result.ERROR_INITIALIZATION_FAILED",
    "vkEnumerateInstanceLayerProperties": "Result.ERROR_INITIALIZATION_FAILED",
    "vkEnumerateInstanceExtensionProperties": "Result.ERROR_INITIALIZATION_FAILED",
    "vkGetInstanceProcAddr": "null",
}

HEADER = """\
// Generated by scripts/generate_loader.py from commands.c3. Do not edit.
module vk::entry_points;
import vk;

alias Lookup = fn void*(ZString name);
"""


def parse_commands(text: str) -> list[dict[str, str]]:
    commands = []
    for line in text.splitlines():
        if not line.startswith("extern fn "):
            continue
        match = EXTERN.match(line)
        if match is None:
            raise ValueError(f"unrecognised extern line: {line}")
        command = match.groupdict()
        params = [p.strip() for p in command["params"].split(",") if p.strip()]
        command["args"] = ", ".join(p.split()[-1] for p in params)
        command["alias"] = "".join(part.capitalize() for part in command["name"].split("_")) + "Fn"
        commands.append(command)
    missing = set(GLOBAL_COMMANDS) - {c["symbol"] for c in commands}
    if missing:
        raise ValueError(f"global commands not found in commands.c3: {sorted(missing)}")
    return commands


def render(commands: list[dict[str, str]]) -> str:
    out = [HEADER]
    for c in commands:
        out.append(f"alias {c['alias']} @private = fn {c['ret']}({c['params']});")
    out.append("")
    out.append("struct CommandTable @private {")
    for c in commands:
        out.append(f"    {c['alias']} {c['name']};")
    out.append("}")
    out.append("")
    out.append("CommandTable table @private;")
    out.append("")
    out.append(
        "<* Resolve every core command through lookup and publish the table only when all resolved.\n"
        "   @param lookup : \"Returns the loader's export of a name, or null.\"\n"
        "   @param missing : \"Receives the first command the loader does not export.\"\n"
        "   @return? vk::LOADER_INCOMPLETE *>"
    )
    out.append("fn void? resolve(Lookup lookup, ZString* missing) {")
    out.append("    CommandTable resolved;")
    for c in commands:
        out.append(f"    resolved.{c['name']} = ({c['alias']})lookup(\"{c['symbol']}\");")
        out.append(f"    if (!resolved.{c['name']}) {{")
        out.append(f"        *missing = \"{c['symbol']}\";")
        out.append("        return vk::LOADER_INCOMPLETE~;")
        out.append("    }")
    out.append("    table = resolved;")
    out.append("}")
    for c in commands:
        out.append("")
        signature = (
            f"fn {c['ret']} {c['name']}({c['params']}) @export(\"{c['symbol']}\") @private"
        )
        call = f"table.{c['name']}({c['args']})"
        fallback = GLOBAL_COMMANDS.get(c["symbol"])
        if fallback is None:
            out.append(f"{signature} => {call};")
            continue
        out.append(f"{signature} {{")
        out.append(f"    if (!vk::ensure_loader()) return {fallback};")
        out.append(f"    return {call};")
        out.append("}")
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the committed file is stale")
    args = parser.parse_args()
    expected = render(parse_commands(COMMANDS.read_text(encoding="utf-8")))
    if args.check:
        actual = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if actual != expected:
            print(f"{OUTPUT.name} is stale: run scripts/generate_loader.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_bytes(expected.encode("utf-8"))
    print(f"wrote {OUTPUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
